"""Turn hotels.json into hotels.js (for index.html) and draw map_pinned.jpg (for README.md).

Run basemap.py first. Prices are Booking.com 3-night totals for Oct 31 – Nov 3, 2026 (resort fee included, tax not).
"""
import json, math, os, re
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..")
TAX = 1.18712          # 11% TAT + 3% Oʻahu TAT + 4.712% GET, charged on room + resort fee
CAP_NIGHT = 500        # all-in budget per night
NIGHTS = 3
APPROX = {"luana": (21.28330, -157.83090)}  # from the street address; not a map pin

SHORT = {"outrigger-reef": "OUTRIGGER Reef", "outrigger-waikiki-beach": "OUTRIGGER Waikīkī Beach", "moana-surfrider": "Moana Surfrider",
         "alohilani": "ʻAlohilani", "hyatt-regency": "Hyatt Regency", "sheraton-waikiki": "Sheraton Waikīkī",
         "hilton-hawaiian-village": "Hilton Hawaiian Village", "waikiki-beach-marriott": "Waikīkī Beach Marriott",
         "prince-waikiki": "Prince Waikīkī", "halepuna": "Halepuna", "halekulani": "Halekulani", "royal-hawaiian": "Royal Hawaiian",
         "ritz-carlton-residences": "Ritz-Carlton Residences", "ka-lai": "Ka Laʻi", "kaimana-beach": "Kaimana Beach",
         "queen-kapiolani": "Queen Kapiʻolani", "park-shore": "Park Shore", "twin-fin": "Twin Fin", "beachcomber": "OUTRIGGER Beachcomber",
         "embassy-suites": "Embassy Suites", "laylow": "The Laylow", "surfjack": "Surfjack", "romer-house": "Romer House",
         "wayfinder": "Wayfinder", "hotel-renew": "Hotel Renew", "lotus-honolulu": "Lotus Honolulu", "hyatt-centric": "Hyatt Centric",
         "hyatt-place": "Hyatt Place", "hilton-waikiki-beach": "Hilton Waikīkī Beach", "shoreline": "Shoreline", "kahala": "The Kahala",
         "turtle-bay": "Turtle Bay", "four-seasons-ko-olina": "Four Seasons Ko Olina", "luana": "Luana Waikīkī"}

def ll2px(lat, lon, z):
    n = 256 * 2**z
    s = math.sin(math.radians(lat))
    return (lon + 180) / 360 * n, (0.5 - math.log((1+s)/(1-s)) / (4*math.pi)) * n

def place(lat, lon, m):
    x, y = ll2px(lat, lon, m["z"])
    return (x - m["x0"]) / m["w"], (y - m["y0"]) / m["h"]

def rooms_of(h):
    found = re.findall(r"([^;]+?): \$([\d,]+) 3-night total", h["rate_note"].split(" -- ")[0])
    out = []
    for label, total in found:
        t = int(total.replace(",", ""))
        out.append({"label": label.strip(), "total": t, "allin": round(t * TAX), "night": round(t * TAX / NIGHTS)})
    return sorted(out, key=lambda r: r["total"])

def main():
    hotels = json.load(open(os.path.join(ROOT, "hotels.json")))
    maps = {k: json.load(open(os.path.join(HERE, f"map_{k}.json"))) for k in ("waikiki", "oahu")}
    out = []
    for h in hotels:
        lat, lon = h["lat"], h["lon"]
        approx = lat is None
        if approx:
            lat, lon = APPROX[h["slug"]]
        fx, fy = place(lat, lon, maps["waikiki"])
        on_waikiki = 0 <= fx <= 1 and 0 <= fy <= 1
        if not on_waikiki:
            fx, fy = place(lat, lon, maps["oahu"])
        rooms = rooms_of(h)
        # the couple wants a king bed: the best room is the dearest king under the cap (usually the best view)
        kings = [r for r in rooms if "king" in r["label"].lower() and "queen only" not in r["label"].lower()]
        under = [r for r in kings if r["night"] <= CAP_NIGHT]
        score = re.search(r"Booking\.com (\d\.\d)/10 \(([\d,]+) reviews", h["scores"])
        out.append({
            "slug": h["slug"], "name": h["name"], "short": SHORT.get(h["slug"], h["name"]), "area": h["area"], "tier": h["tier"],
            "lat": lat, "lon": lon, "approx": approx, "map": "waikiki" if on_waikiki else "oahu", "x": round(fx, 4), "y": round(fy, 4),
            "beach": h["beach"], "fee": h["resort_fee"], "balconies": h["balconies"], "adults": h["adults_only"],
            "score": float(score.group(1)) if score else None, "reviews": int(score.group(2).replace(",", "")) if score else None,
            "rooms": rooms, "cheapest": rooms[0] if rooms else None, "best": under[-1] if under else None,
            "fits": bool(under), "pros": h["pros"], "cons": h["cons"], "deal": h["deal"], "verdict": h["verdict"],
            "url": h["url"], "sources": h["sources"],
        })
    # number the Waikīkī pins west to east along the shore, then the out-of-town ones
    out.sort(key=lambda h: (h["map"] != "waikiki", h["lon"]))
    for i, h in enumerate(out, 1):
        h["n"] = i
    meta = {"tax": TAX, "cap_night": CAP_NIGHT, "nights": NIGHTS, "fetched": "2026-10-18",
            "dates": "Sat Oct 31 – Tue Nov 3, 2026", "maps": maps}
    with open(os.path.join(ROOT, "hotels.js"), "w") as f:
        f.write("// Generated by tools/build.py from hotels.json. Do not edit by hand.\n")
        f.write("window.HOTEL_META = " + json.dumps(meta, ensure_ascii=False) + ";\n")
        f.write("window.HOTELS = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n")
    draw_static(out, maps["waikiki"])
    print(len(out), "hotels;", sum(h["fits"] for h in out), "have a king room under the cap")

def draw_static(hotels, m):
    img = Image.open(os.path.join(ROOT, "map_waikiki.jpg")).convert("RGBA")
    ov = Image.new("RGBA", img.size, (0, 0, 0, 0)); d = ImageDraw.Draw(ov)
    F = "/System/Library/Fonts/Supplemental/Arial Unicode.ttf"
    fn, fl = ImageFont.truetype(F, 22), ImageFont.truetype(F, 20)
    for h in hotels:
        if h["map"] != "waikiki":
            continue
        x, y = h["x"] * m["w"], h["y"] * m["h"]
        fill = "#0f766e" if h["fits"] else "#6b7280"
        if h["slug"] == "outrigger-reef":
            fill = "#be185d"
        d.ellipse([x-19, y-19, x+19, y+19], fill=fill, outline="white", width=4)
        d.text((x, y), str(h["n"]), font=fn, fill="white", anchor="mm")
    d.rectangle([0, 0, m["w"], 54], fill=(255, 255, 255, 230))
    d.text((18, 27), "Waikīkī hotels · pink = current pick · teal = king room under $500/night all-in · grey = over",
           font=fl, fill="#111", anchor="lm")
    att = "Map: Esri, HERE, Garmin, © OpenStreetMap contributors"
    d.text((m["w"]-10, m["h"]-14), att, font=ImageFont.truetype(F, 15), fill="#333", anchor="rm")
    Image.alpha_composite(img, ov).convert("RGB").save(os.path.join(ROOT, "map_pinned.jpg"), quality=82, optimize=True)

if __name__ == "__main__":
    main()
